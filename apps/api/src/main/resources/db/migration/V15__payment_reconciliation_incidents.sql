-- BKL-041: never silently discard ambiguous or late sandbox authorizations.
-- Idempotent per (order, reason). Incidents are not proof of payment.
CREATE TABLE payment_reconciliation_incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    reason VARCHAR(36) NOT NULL
        CHECK (reason IN ('AMBIGUOUS_AUTHORIZATION',
            'AWAITING_VERIFIED_APPROVAL','LATE_APPROVAL','EVIDENCE_MISMATCH')),
    webhook_event_id BIGINT REFERENCES payment_webhook_events(id)
        ON DELETE RESTRICT,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_payment_incident_order_reason UNIQUE(order_id, reason)
);
CREATE INDEX idx_payment_incident_recent
    ON payment_reconciliation_incidents(detected_at DESC, id DESC);
