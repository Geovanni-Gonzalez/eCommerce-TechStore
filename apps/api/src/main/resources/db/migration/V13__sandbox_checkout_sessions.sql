-- BKL-037: sesión de redirección al checkout simulado, no a un banco.
-- La clave bearer de navegación nunca se almacena en claro.
CREATE TABLE sandbox_checkout_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_attempt_id BIGINT NOT NULL UNIQUE
        REFERENCES payment_attempts(id) ON DELETE RESTRICT,
    token_hash CHAR(64) NOT NULL UNIQUE
        CHECK (token_hash ~ '^[A-F0-9]{64}$'),
    expires_at TIMESTAMPTZ NOT NULL,
    redeemed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_sandbox_checkout_session_expiry CHECK (expires_at > created_at),
    CONSTRAINT chk_sandbox_checkout_redeemed CHECK (
        redeemed_at IS NULL OR redeemed_at >= created_at)
);
CREATE INDEX idx_sandbox_checkout_session_expiry
    ON sandbox_checkout_sessions(expires_at) WHERE redeemed_at IS NULL;
