CREATE FUNCTION shipping_guard_manual_transition() RETURNS TRIGGER
LANGUAGE plpgsql AS $shipping_guard$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'El registro de envío es inmutable' USING ERRCODE='23514';
    END IF;
    IF OLD.id IS DISTINCT FROM NEW.id
       OR OLD.order_id IS DISTINCT FROM NEW.order_id
       OR OLD.fulfillment_method IS DISTINCT FROM NEW.fulfillment_method
       OR OLD.opened_by_user_id IS DISTINCT FROM NEW.opened_by_user_id
       OR OLD.registered_at IS DISTINCT FROM NEW.registered_at
       OR NEW.last_changed_by_user_id IS NULL
       OR NOT (
           (OLD.status='PENDING_MANUAL' AND NEW.status='IN_TRANSIT')
           OR (OLD.status='IN_TRANSIT' AND NEW.status='DELIVERED')
       ) THEN
        RAISE EXCEPTION 'Transición logística manual no permitida'
            USING ERRCODE='23514';
    END IF;
    NEW.status_updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$shipping_guard$;
CREATE TRIGGER trg_shipping_guard_manual_transition
BEFORE UPDATE OR DELETE ON shipments FOR EACH ROW
EXECUTE FUNCTION shipping_guard_manual_transition();

CREATE FUNCTION shipping_audit_manual_status() RETURNS TRIGGER
LANGUAGE plpgsql AS $shipping_audit$
BEGIN
    IF TG_OP='INSERT' THEN
        INSERT INTO shipment_status_history
            (shipment_id,from_status,to_status,actor_user_id,reason,changed_at)
        VALUES (NEW.id,NULL,'PENDING_MANUAL',NEW.opened_by_user_id,
                'MANUAL_REGISTERED',NEW.registered_at);
    ELSIF OLD.status IS DISTINCT FROM NEW.status THEN
        INSERT INTO shipment_status_history
            (shipment_id,from_status,to_status,actor_user_id,reason,changed_at)
        VALUES (NEW.id,OLD.status,NEW.status,NEW.last_changed_by_user_id,
                CASE NEW.status WHEN 'IN_TRANSIT' THEN 'MANUAL_DISPATCH'
                    WHEN 'DELIVERED' THEN 'MANUAL_DELIVERY' END,
                NEW.status_updated_at);
    END IF;
    RETURN NEW;
END;
$shipping_audit$;
CREATE TRIGGER trg_shipping_audit_insert AFTER INSERT ON shipments
FOR EACH ROW EXECUTE FUNCTION shipping_audit_manual_status();
CREATE TRIGGER trg_shipping_audit_update AFTER UPDATE OF status ON shipments
FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION shipping_audit_manual_status();
