    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES shipments(id) ON DELETE RESTRICT,
    from_status VARCHAR(24),
    to_status VARCHAR(24) NOT NULL,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reason VARCHAR(24) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_shipment_status_once UNIQUE (shipment_id,to_status),
    CONSTRAINT chk_shipment_history_steps CHECK (
        (from_status IS NULL AND to_status='PENDING_MANUAL'
            AND reason='MANUAL_REGISTERED')
        OR (from_status='PENDING_MANUAL' AND to_status='IN_TRANSIT'
            AND reason='MANUAL_DISPATCH')
        OR (from_status='IN_TRANSIT' AND to_status='DELIVERED'
            AND reason='MANUAL_DELIVERY')
    )
);
