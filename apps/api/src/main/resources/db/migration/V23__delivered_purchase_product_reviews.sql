-- BKL-050: reseñas verificadas por compra y entrega MANUAL registrada.
-- Un DELIVERED generado en SIMULATOR no demuestra recepción física.
-- Migración nueva: V1-V22 permanecen sin cambios.
CREATE TABLE product_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(1000) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_product_reviews_comment CHECK (
        CHAR_LENGTH(comment) BETWEEN 5 AND 1000
        AND comment = BTRIM(comment)
        AND comment !~ '[[:cntrl:]]'
    )
);
-- Esta restricción también resiste dos solicitudes simultáneas de la API.
CREATE UNIQUE INDEX uq_product_reviews_one_active_per_customer_product
    ON product_reviews (user_id, product_id) WHERE active;
CREATE INDEX idx_product_reviews_product_active
    ON product_reviews (product_id, created_at DESC, id DESC) WHERE active;

-- Segunda barrera de seguridad: INSERT/UPDATE no puede crear o activar una
-- reseña sin compra histórica de ese producto y entrega declarada MANUAL.
-- La fuente SIMULATOR nunca permite reseñar aunque su status sea DELIVERED.
CREATE FUNCTION reviews_require_genuine_delivered_purchase() RETURNS TRIGGER
LANGUAGE plpgsql AS $review_eligible$
BEGIN
    IF NEW.active AND NOT EXISTS (
        SELECT 1
        FROM orders o
        JOIN order_items oi ON oi.order_id = o.id
        JOIN shipments s ON s.order_id = o.id
        JOIN shipment_status_history h ON h.shipment_id = s.id
        WHERE o.user_id = NEW.user_id
          AND o.status = 'CONFIRMED'
          AND oi.product_id = NEW.product_id
          AND s.fulfillment_method = 'MANUAL'
          AND s.status = 'DELIVERED'
          AND h.from_status = 'IN_TRANSIT'
          AND h.to_status = 'DELIVERED'
          AND h.reason = 'MANUAL_DELIVERY'
    ) THEN
        RAISE EXCEPTION 'Reseña requiere compra entregada manualmente'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$review_eligible$;
CREATE TRIGGER trg_reviews_require_delivered_purchase
BEFORE INSERT OR UPDATE ON product_reviews
FOR EACH ROW EXECUTE FUNCTION reviews_require_genuine_delivered_purchase();
