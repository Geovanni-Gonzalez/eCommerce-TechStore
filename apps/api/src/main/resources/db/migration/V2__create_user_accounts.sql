-- BKL-014: usuarios y roles. No modificar V1 aplicada anteriormente.
-- El registro público (BKL-015) únicamente podrá crear usuarios CLIENTE.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(60) NOT NULL,
    role VARCHAR(10) NOT NULL DEFAULT 'CLIENTE',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_users_email_normalized CHECK (
        email = LOWER(BTRIM(email))
        AND email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'
    ),
    CONSTRAINT chk_users_password_bcrypt CHECK (
        password_hash ~ '^[$]2[aby][$][0-9]{2}[$][./A-Za-z0-9]{53}$'
    ),
    CONSTRAINT chk_users_role CHECK (role IN ('CLIENTE', 'ADMIN'))
);

-- Como el email se almacena normalizado en minúsculas, esta restricción
-- impide también duplicados con mayúsculas y espacios de entrada.
CREATE UNIQUE INDEX ux_users_email ON users (email);
CREATE INDEX idx_users_role ON users (role);
