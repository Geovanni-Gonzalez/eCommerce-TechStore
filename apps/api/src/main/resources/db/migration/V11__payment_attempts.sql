-- Sin datos de tarjetas ni credenciales. No confirma pedidos ni consume reservas.
CREATE UNIQUE INDEX uq_orders_id_owner ON orders(id, user_id);

CREATE TABLE payment_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    idempotency_key_hash CHAR(64) NOT NULL
        CHECK (idempotency_key_hash ~ '^[A-F0-9]{64}$'),
    total_crc NUMERIC(14,2) NOT NULL CHECK (total_crc > 0),
    status VARCHAR(24) NOT NULL
        CHECK (status IN (
            'STARTED', 'SIMULATED_APPROVED', 'SIMULATED_DECLINED',
            'UNAVAILABLE', 'UNKNOWN')),
    provider_reference VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payment_attempt_order_owner
        FOREIGN KEY (order_id, user_id)
        REFERENCES orders(id, user_id) ON DELETE RESTRICT,
    CONSTRAINT uq_payment_attempt_user_key
        UNIQUE (user_id, idempotency_key_hash),
    CONSTRAINT uq_payment_attempt_provider_ref UNIQUE (provider_reference),
    CONSTRAINT chk_payment_attempt_reference CHECK (
        (status IN ('STARTED', 'UNAVAILABLE', 'UNKNOWN')
            AND provider_reference IS NULL)
        OR (status IN ('SIMULATED_APPROVED', 'SIMULATED_DECLINED')
            AND provider_reference IS NOT NULL
            AND CHAR_LENGTH(provider_reference) BETWEEN 8 AND 64))
);

-- Una autorización simulada aprobada o un intento incierto/activo
-- bloquean nuevos intentos con claves distintas para el mismo pedido.
CREATE UNIQUE INDEX uq_payment_attempt_order_active
    ON payment_attempts(order_id)
    WHERE status IN ('STARTED', 'SIMULATED_APPROVED', 'UNKNOWN');

CREATE INDEX idx_payment_attempt_order_created
    ON payment_attempts(order_id, created_at DESC, id DESC);
