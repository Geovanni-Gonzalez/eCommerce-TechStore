-- BKL-047: registro logístico manual. NO representa entrega real,
-- guía de transporte, estimación ni confirmación de pago.
-- La dirección continúa solo en el snapshot del pedido (V6).
CREATE TABLE shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    fulfillment_method VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING_MANUAL',
    opened_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_shipments_order UNIQUE (order_id),
    CONSTRAINT chk_shipments_method CHECK (fulfillment_method = 'MANUAL'),
    CONSTRAINT chk_shipments_status CHECK (status = 'PENDING_MANUAL')
);

-- No se permite registrar un envío para un pedido PENDING o CANCELLED
-- aunque se intente eludir la API. La aprobación de pago no se infiere aquí.
CREATE FUNCTION shipping_require_confirmed_order() RETURNS TRIGGER
LANGUAGE plpgsql AS $shipping_confirmed$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM orders o
        WHERE o.id = NEW.order_id AND o.status = 'CONFIRMED'
    ) THEN
        RAISE EXCEPTION 'Solo pedidos confirmados admiten registro de envío'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$shipping_confirmed$;
CREATE TRIGGER trg_shipping_require_confirmed_order
BEFORE INSERT ON shipments
FOR EACH ROW EXECUTE FUNCTION shipping_require_confirmed_order();

-- Antes de BKL-048 los registros de envío son inmutables; no existen
-- transiciones públicas ni administrativas para simular entregas.
CREATE FUNCTION shipping_reject_record_mutation() RETURNS TRIGGER
LANGUAGE plpgsql AS $shipping_immutable$
BEGIN
    RAISE EXCEPTION 'El registro logístico inicial es inmutable'
        USING ERRCODE = '23514';
END;
$shipping_immutable$;
CREATE TRIGGER trg_shipping_initial_registration_immutable
BEFORE UPDATE OR DELETE ON shipments
FOR EACH ROW EXECUTE FUNCTION shipping_reject_record_mutation();
CREATE INDEX idx_shipments_registered_at ON shipments (registered_at DESC, id DESC);
