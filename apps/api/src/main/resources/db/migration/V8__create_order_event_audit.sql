-- BKL-068: evidencia de un Observer de pedidos posterior al commit.
-- Sin PII de dirección/cliente. V1-V7 son inmutables.
CREATE TABLE order_event_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    event_type VARCHAR(32) NOT NULL
        CHECK (event_type = 'ORDER_CREATED'),
    total_crc NUMERIC(14,2) NOT NULL CHECK (total_crc >= 0),
    observed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_order_event_audit UNIQUE (order_id, event_type)
);

CREATE INDEX idx_order_event_audit_observed_at
    ON order_event_audit (observed_at);
