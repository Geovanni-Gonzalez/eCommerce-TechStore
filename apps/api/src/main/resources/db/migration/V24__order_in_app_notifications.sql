-- BKL-053: notificaciones persistidas, sin PII ni supuestos de email entregado.
CREATE TABLE order_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    event_type VARCHAR(32) NOT NULL CHECK (event_type IN ('ORDER_RECEIVED')),
    message VARCHAR(180) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_order_notification_event UNIQUE (order_id,event_type)
);
CREATE INDEX idx_order_notifications_owner ON order_notifications(user_id,order_id,id);
