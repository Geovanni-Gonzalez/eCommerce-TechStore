-- BKL-038: eventos auténticos del sandbox, sin pagos reales ni
-- transición automática de pedidos/stock. Una notificación terminal por intento.
CREATE TABLE payment_webhook_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(16) NOT NULL DEFAULT 'SANDBOX'
        CHECK (provider = 'SANDBOX'),
    provider_event_id VARCHAR(80) NOT NULL
        CHECK (provider_event_id ~ '^[A-Za-z0-9][A-Za-z0-9_-]{7,79}$'),
    payment_attempt_id BIGINT NOT NULL REFERENCES payment_attempts(id)
        ON DELETE RESTRICT,
    payload_sha256 CHAR(64) NOT NULL
        CHECK (payload_sha256 ~ '^[A-F0-9]{64}$'),
    outcome VARCHAR(16) NOT NULL CHECK (outcome IN ('APPROVED', 'DECLINED')),
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_webhook_provider_event UNIQUE (provider, provider_event_id),
    CONSTRAINT uq_webhook_attempt_terminal UNIQUE (payment_attempt_id)
);
CREATE INDEX idx_payment_webhook_attempt_time
    ON payment_webhook_events (payment_attempt_id, received_at DESC);
