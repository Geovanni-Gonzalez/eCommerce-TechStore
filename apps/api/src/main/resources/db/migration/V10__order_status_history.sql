-- BKL-045: historial de estados con actor y motivo, no confundir con Observer V8.
CREATE TABLE order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    from_status VARCHAR(16) CHECK (from_status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    to_status VARCHAR(16) NOT NULL CHECK (to_status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    actor_type VARCHAR(12) NOT NULL CHECK (actor_type IN ('CLIENT', 'ADMIN', 'SYSTEM')),
    actor_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    reason VARCHAR(24) NOT NULL
        CHECK (reason IN ('CREATED', 'BASELINE', 'CLIENT_CANCEL', 'ADMIN_CANCEL', 'EXPIRED')),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_order_history_actor CHECK (
        (actor_type = 'SYSTEM' AND actor_id IS NULL)
        OR (actor_type IN ('CLIENT', 'ADMIN') AND actor_id IS NOT NULL)),
    CONSTRAINT chk_order_history_actual_change CHECK (
        from_status IS NULL OR from_status <> to_status)
);
-- Una sola anotación inicial; los cambios posteriores conservan el orden por id.
CREATE UNIQUE INDEX uq_order_status_initial
    ON order_status_history(order_id) WHERE from_status IS NULL;
CREATE INDEX idx_order_status_history_order
    ON order_status_history(order_id, id);

-- Para pedidos antiguos solo registramos la observación inicial del estado
-- actual (BASELINE), sin inventar transiciones ni autores históricos.
INSERT INTO order_status_history
    (order_id, from_status, to_status, actor_type, actor_id, reason, changed_at)
SELECT id, NULL, status, 'SYSTEM', NULL, 'BASELINE', created_at
FROM orders;
