-- BKL-030: pedido persistente y snapshots comerciales inmutables.
-- V1-V5 no se editan. El carrito no es un pedido y no se reserva stock aquí.
CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    payment_mode VARCHAR(16) NOT NULL DEFAULT 'SIMULATED',
    ship_province VARCHAR(80) NOT NULL,
    ship_canton VARCHAR(80) NOT NULL,
    ship_district VARCHAR(80) NOT NULL,
    ship_details VARCHAR(300) NOT NULL,
    ship_recipient_name VARCHAR(120) NOT NULL,
    ship_phone VARCHAR(24) NOT NULL,
    subtotal_crc NUMERIC(14,2) NOT NULL CHECK (subtotal_crc >= 0),
    shipping_crc NUMERIC(14,2) NOT NULL CHECK (shipping_crc >= 0),
    tax_crc NUMERIC(14,2) NOT NULL CHECK (tax_crc >= 0),
    total_crc NUMERIC(14,2) NOT NULL CHECK (total_crc >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_orders_status CHECK (status IN ('PENDING','CONFIRMED','CANCELLED')),
    CONSTRAINT chk_orders_simulated_only CHECK (payment_mode = 'SIMULATED'),
    CONSTRAINT chk_orders_total CHECK (total_crc = subtotal_crc + shipping_crc + tax_crc),
    CONSTRAINT chk_orders_address CHECK (
        CHAR_LENGTH(ship_province) BETWEEN 1 AND 80
        AND CHAR_LENGTH(ship_canton) BETWEEN 1 AND 80
        AND CHAR_LENGTH(ship_district) BETWEEN 1 AND 80
        AND CHAR_LENGTH(ship_details) BETWEEN 5 AND 300
        AND CHAR_LENGTH(ship_recipient_name) BETWEEN 2 AND 120
        AND CHAR_LENGTH(ship_phone) BETWEEN 8 AND 24
        AND ship_province = BTRIM(ship_province)
        AND ship_canton = BTRIM(ship_canton)
        AND ship_district = BTRIM(ship_district)
        AND ship_details = BTRIM(ship_details)
        AND ship_recipient_name = BTRIM(ship_recipient_name)
        AND ship_phone = BTRIM(ship_phone)
        AND ship_province !~ '[[:cntrl:]]'
        AND ship_canton !~ '[[:cntrl:]]'
        AND ship_district !~ '[[:cntrl:]]'
        AND ship_details !~ '[[:cntrl:]]'
        AND ship_recipient_name !~ '[[:cntrl:]]'
        AND ship_phone !~ '[[:cntrl:]]'
    )
);

-- Las líneas son snapshots históricos, independientes de mutaciones en
-- products.name/price_crc. product_id se conserva como identificador histórico
-- (sin FK): la eliminación futura del catálogo no reescribe pedidos pasados.
CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    line_number INTEGER NOT NULL CHECK (line_number > 0),
    product_id BIGINT NOT NULL CHECK (product_id > 0),
    product_name VARCHAR(160) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
    unit_price_crc NUMERIC(12,2) NOT NULL CHECK (unit_price_crc >= 0),
    line_total_crc NUMERIC(14,2) NOT NULL CHECK (line_total_crc >= 0),
    CONSTRAINT uq_order_items_position UNIQUE (order_id, line_number),
    CONSTRAINT uq_order_items_product UNIQUE (order_id, product_id),
    CONSTRAINT chk_order_items_total CHECK (
        line_total_crc = unit_price_crc * quantity
    ),
    CONSTRAINT chk_order_items_name CHECK (
        CHAR_LENGTH(product_name) BETWEEN 1 AND 160
        AND product_name = BTRIM(product_name)
        AND product_name !~ '[[:cntrl:]]'
    )
);

CREATE INDEX idx_orders_user_created ON orders (user_id, created_at DESC, id DESC);
CREATE INDEX idx_order_items_order ON order_items (order_id, line_number);
