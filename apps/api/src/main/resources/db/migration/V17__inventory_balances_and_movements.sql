-- BKL-025: balance real a partir del stock disponible y las reservas existentes.
-- products.stock ya significa DISPONIBLE (BKL-033): decrece al reservar,
-- se restituye al cancelar y permanece descontado al consumir la reserva.
-- NO duplicar estos saldos en columnas editables: toda lectura se calcula
-- en una misma instantánea MVCC y no existe riesgo de contador desfasado.
CREATE VIEW inventory_balances AS
SELECT p.id AS product_id,
       p.stock::BIGINT AS available_stock,
       COALESCE(r.reserved_stock, 0)::BIGINT AS reserved_stock,
       (p.stock::BIGINT + COALESCE(r.reserved_stock, 0)) AS physical_stock
FROM products p
LEFT JOIN LATERAL (
    SELECT COALESCE(SUM(sr.quantity::BIGINT), 0) AS reserved_stock
    FROM stock_reservations sr
    WHERE sr.product_id = p.id AND sr.status = 'RESERVED'
) r ON TRUE;

-- Libro mayor append-only: la auditoría conserva el ID de producto aun si
-- en el futuro se retira físicamente del catálogo (sin FK a products).
-- Los pedidos no pueden eliminarse según el historial del sistema.
CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL CHECK (product_id > 0),
    order_id BIGINT REFERENCES orders(id) ON DELETE RESTRICT,
    kind VARCHAR(16) NOT NULL
        CHECK (kind IN (
            'OPENING', 'RESERVED', 'RELEASED', 'CONSUMED',
            'ADJUSTMENT_IN', 'ADJUSTMENT_OUT'
        )),
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    available_delta BIGINT NOT NULL,
    reserved_delta BIGINT NOT NULL,
    physical_delta BIGINT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_inventory_movement_balance CHECK (
        physical_delta = available_delta + reserved_delta
    ),
    CONSTRAINT chk_inventory_movement_kind CHECK (
        (kind = 'OPENING' AND order_id IS NULL
            AND physical_delta = quantity
            AND available_delta >= 0 AND reserved_delta >= 0)
        OR (kind = 'RESERVED' AND order_id IS NOT NULL
            AND physical_delta = 0
            AND available_delta = -quantity AND reserved_delta = quantity)
        OR (kind = 'RELEASED' AND order_id IS NOT NULL
            AND physical_delta = 0
            AND available_delta = quantity AND reserved_delta = -quantity)
        OR (kind = 'CONSUMED' AND order_id IS NOT NULL
            AND physical_delta = -quantity
            AND available_delta = 0 AND reserved_delta = -quantity)
        OR (kind = 'ADJUSTMENT_IN' AND order_id IS NULL
            AND physical_delta = quantity
            AND available_delta = quantity AND reserved_delta = 0)
        OR (kind = 'ADJUSTMENT_OUT' AND order_id IS NULL
            AND physical_delta = -quantity
            AND available_delta = -quantity AND reserved_delta = 0)
    )
);

CREATE INDEX idx_inventory_movements_product_recorded
    ON inventory_movements (product_id, recorded_at DESC, id DESC);
CREATE INDEX idx_inventory_movements_order
    ON inventory_movements (order_id, id) WHERE order_id IS NOT NULL;
CREATE UNIQUE INDEX uq_inventory_movement_reservation_lifecycle
    ON inventory_movements (order_id, product_id, kind)
    WHERE order_id IS NOT NULL;

-- La migración no reconstruye eventos previos que no fueron auditados.
-- Registra UNA fotografía inicial del stock actual y reservas activas.
-- Productos sin existencias ni reservas no requieren movimiento inicial.
INSERT INTO inventory_movements (
    product_id, kind, quantity, available_delta, reserved_delta, physical_delta
)
SELECT product_id, 'OPENING', physical_stock,
       available_stock, reserved_stock, physical_stock
FROM inventory_balances WHERE physical_stock > 0;

-- Los productos creados mediante SQL/ADMIN con stock positivo también
-- generan evento de apertura. Los nuevos productos ADMIN comienzan en cero.
CREATE FUNCTION inventory_audit_product_insert() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.stock > 0 THEN
        INSERT INTO inventory_movements (
            product_id,kind,quantity,available_delta,reserved_delta,physical_delta
        ) VALUES (NEW.id,'OPENING',NEW.stock,NEW.stock,0,NEW.stock);
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_inventory_product_opening
AFTER INSERT ON products
FOR EACH ROW EXECUTE FUNCTION inventory_audit_product_insert();

-- Las reservas de checkout existentes siguen operando igual.
-- El trigger inserta los eventos en la MISMA transacción que el pedido.
-- Fallar una auditoría provoca rollback de la reserva, nunca un saldo oculto.
CREATE FUNCTION inventory_audit_reservation() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' AND NEW.status = 'RESERVED' THEN
        INSERT INTO inventory_movements (
            product_id,order_id,kind,quantity,
            available_delta,reserved_delta,physical_delta
        ) VALUES (
            NEW.product_id,NEW.order_id,'RESERVED',NEW.quantity,
            -NEW.quantity,NEW.quantity,0
        );
    ELSIF TG_OP = 'UPDATE' AND OLD.status = 'RESERVED'
          AND NEW.status = 'RELEASED' THEN
        INSERT INTO inventory_movements (
            product_id,order_id,kind,quantity,
            available_delta,reserved_delta,physical_delta
        ) VALUES (
            NEW.product_id,NEW.order_id,'RELEASED',NEW.quantity,
            NEW.quantity,-NEW.quantity,0
        );
    ELSIF TG_OP = 'UPDATE' AND OLD.status = 'RESERVED'
          AND NEW.status = 'CONSUMED' THEN
        INSERT INTO inventory_movements (
            product_id,order_id,kind,quantity,
            available_delta,reserved_delta,physical_delta
        ) VALUES (
            NEW.product_id,NEW.order_id,'CONSUMED',NEW.quantity,
            0,-NEW.quantity,-NEW.quantity
        );
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_inventory_reservation_created
AFTER INSERT ON stock_reservations
FOR EACH ROW EXECUTE FUNCTION inventory_audit_reservation();
CREATE TRIGGER trg_inventory_reservation_status
AFTER UPDATE OF status ON stock_reservations
FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION inventory_audit_reservation();

-- Las cantidades y claves de una reserva no pueden cambiar después
-- de su creación, y una reserva terminal nunca vuelve a RESERVED.
-- Sin este guard sería posible alterar el saldo sin dejar un evento.
CREATE FUNCTION inventory_guard_reservation_mutation() RETURNS TRIGGER
LANGUAGE plpgsql AS $
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'No se pueden eliminar reservas históricas'
            USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'RESERVED' THEN
            RAISE EXCEPTION 'Una reserva nueva debe comenzar RESERVED'
                USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    IF OLD.order_id IS DISTINCT FROM NEW.order_id
       OR OLD.product_id IS DISTINCT FROM NEW.product_id
       OR OLD.quantity IS DISTINCT FROM NEW.quantity THEN
        RAISE EXCEPTION 'La identidad y cantidad de la reserva son inmutables'
            USING ERRCODE = '23514';
    END IF;
    IF OLD.status IS DISTINCT FROM NEW.status
       AND NOT (OLD.status = 'RESERVED'
            AND NEW.status IN ('RELEASED', 'CONSUMED')) THEN
        RAISE EXCEPTION 'Transición de reserva no permitida'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$;
CREATE TRIGGER trg_inventory_reservation_integrity
BEFORE INSERT OR UPDATE OR DELETE ON stock_reservations
FOR EACH ROW EXECUTE FUNCTION inventory_guard_reservation_mutation();

-- La bitácora de movimientos no puede reescribirse ni borrarse.
CREATE FUNCTION inventory_reject_history_mutation() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Los movimientos de inventario son inmutables'
        USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER trg_inventory_movements_immutable
BEFORE UPDATE OR DELETE ON inventory_movements
FOR EACH ROW EXECUTE FUNCTION inventory_reject_history_mutation();
